// Converts china-division JSON (provinces/cities/areas) into a compact TS module.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = resolve(root, 'node_modules/china-division');

function load(name) {
  const candidates = [`${name}.json`, `dist/${name}.json`, `data/${name}.json`];
  for (const rel of candidates) {
    const p = resolve(pkg, rel);
    if (existsSync(p)) return JSON.parse(readFileSync(p, 'utf8'));
  }
  throw new Error(`china-division: ${name}.json not found in ${pkg}`);
}

// Each row: [code, name, parentCode]
const toRows = (list, parentKey) =>
  list.map((r) => [r.code, r.name, parentKey ? r[parentKey] : '']);

const provinces = toRows(load('provinces'), null);
const cities = toRows(load('cities'), 'provinceCode');
const areas = toRows(load('areas'), 'cityCode');

const out = `// AUTO-GENERATED by scripts/build-region.mjs from china-division. Do not edit.
export type RegionRow = [code: string, name: string, parent: string];
export const PROVINCES: RegionRow[] = ${JSON.stringify(provinces)};
export const CITIES: RegionRow[] = ${JSON.stringify(cities)};
export const AREAS: RegionRow[] = ${JSON.stringify(areas)};
`;

writeFileSync(resolve(root, 'src/core/generators/region-data.ts'), out);
console.log(`[region] provinces=${provinces.length} cities=${cities.length} areas=${areas.length}`);
